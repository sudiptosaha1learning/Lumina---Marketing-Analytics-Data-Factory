"use client";

import { useState } from "react";
import {
  ArrowLeft, MapPin, Star, Users, DollarSign, ChevronRight,
  User, Car, TrendingUp, AlertTriangle, Briefcase, Clock,
  RefreshCw, Target, Sparkles, X, CheckCircle, Phone,
  Mail, MessageSquare, Crown, Activity
} from "lucide-react";
import { type Mission, type RetailerData, type CustomerProfile, type Region } from "@/lib/dashboard-data";
import { cn } from "@/lib/utils";

interface RetailerDrillDownProps {
  mission: Mission;
  region: Region;
  onBack: () => void;
}

const tierColors = {
  "Tier 1": { color: "#f59e0b", bg: "rgba(245,158,11,0.12)", border: "rgba(245,158,11,0.3)" },
  "Tier 2": { color: "#3b82f6", bg: "rgba(59,130,246,0.12)", border: "rgba(59,130,246,0.3)" },
  "Tier 3": { color: "#6b7280", bg: "rgba(107,114,128,0.12)", border: "rgba(107,114,128,0.3)" },
};

export function RetailerDrillDown({ mission, region, onBack }: RetailerDrillDownProps) {
  const [selectedRetailer, setSelectedRetailer] = useState<RetailerData | null>(null);
  const [selectedCustomer, setSelectedCustomer] = useState<CustomerProfile | null>(null);
  const [scriptGenerated, setScriptGenerated] = useState<string | null>(null);
  const [generatingScript, setGeneratingScript] = useState(false);

  const filteredRetailers = mission.retailers.filter(
    (r) => region === "Global" || r.region === region
  );

  const handleGenerateScript = (customer: CustomerProfile) => {
    setGeneratingScript(true);
    setTimeout(() => {
      setScriptGenerated(
        `BESPOKE CONCIERGE SCRIPT — ${customer.name} — ${new Date().toLocaleDateString("en-GB", { day: "2-digit", month: "short", year: "numeric" })}\n\n` +
        `OPENING:\n"Good [morning/afternoon], ${customer.name}. This is [RM Name] from ${selectedRetailer?.name}, calling on behalf of your dedicated JLR Private Client team. I'm reaching out because we've identified a very specific opportunity that I believe is exceptionally well-timed for you."\n\n` +
        `PERSONALISATION HOOK:\nReference: ${customer.currentVehicle} (${customer.currentVariant}) — equity position: ${customer.buybackEquity}\n\n` +
        `VALUE PROPOSITION:\n"Your current ${customer.currentVehicle} is performing exceptionally in today's market — our specialists have identified a ${customer.buybackEquity} equity advantage that, combined with our current Range Rover Electric priority allocation programme, creates a genuinely compelling financial case that may not be available beyond next quarter."\n\n` +
        `MISSION CONTEXT:\n${mission.title}\n"${mission.tagline}"\n\n` +
        `RECOMMENDED NEXT STEP:\n${customer.recommendedAction}\n\n` +
        `CONTACT PREFERENCE:\nBest window: ${customer.contactWindow}\nPreferred channel: ${customer.preferredChannel}\n\n` +
        `OBJECTION HANDLING:\n• If 'not the right time': "I completely understand. The equity position I mentioned is time-limited — our Q3 allocation closes 30 September. Would it help if I arranged a no-obligation private viewing at a time that suits?"\n• If 'happy with current vehicle': "That speaks to your excellent choice. This programme is specifically designed for our most valued clients who are already satisfied — it's about maximising the financial advantage your current vehicle has built."\n\nCLOSING:\n"Given your tenure of ${customer.tenure} with JLR, you'll have first access. I'll follow this up with a personalised proposal document — what email address should I use?"\n\n— Generated by Meridian Intelligence Engine v3.4`
      );
      setGeneratingScript(false);
    }, 1800);
  };

  return (
    <div className="space-y-5">
      {/* Breadcrumb Header */}
      <div className="flex items-center gap-3">
        <button
          onClick={onBack}
          className="flex items-center gap-2 px-3 py-1.5 rounded-lg text-white/50 hover:text-white/80 hover:bg-white/[0.06] transition-all text-sm"
          style={{ border: "1px solid rgba(255,255,255,0.08)" }}
        >
          <ArrowLeft className="w-3.5 h-3.5" />
          Mission Command
        </button>
        <ChevronRight className="w-3.5 h-3.5 text-white/25" />
        <span className="text-white/60 text-sm font-medium">{mission.title}</span>
        <ChevronRight className="w-3.5 h-3.5 text-white/25" />
        <span className="text-white/40 text-sm">Retailer Intelligence</span>
      </div>

      {/* Mission Summary Strip */}
      <div className="flex items-center gap-4 p-4 rounded-2xl flex-wrap"
        style={{ background: `rgba(${hexToRgb(mission.color)}, 0.07)`, border: `1px solid rgba(${hexToRgb(mission.color)}, 0.22)` }}>
        <div className="w-8 h-8 rounded-xl flex items-center justify-center"
          style={{ background: `rgba(${hexToRgb(mission.color)}, 0.2)` }}>
          <Target className="w-4 h-4" style={{ color: mission.color }} />
        </div>
        <div className="flex-1 min-w-0">
          <div className="text-white font-semibold text-sm font-heading truncate">{mission.title}</div>
          <div className="text-white/40 text-xs">"{mission.tagline}"</div>
        </div>
        <div className="flex gap-4 flex-shrink-0 flex-wrap">
          {[
            { label: "Revenue", value: mission.projectedRevenue[region] },
            { label: "Customers", value: mission.targetCustomers[region].toLocaleString() },
            { label: "Conv.", value: mission.conversionRate[region] },
          ].map((s) => (
            <div key={s.label} className="text-center">
              <div className="text-white font-bold text-sm font-heading">{s.value}</div>
              <div className="text-white/35 text-[10px]">{s.label}</div>
            </div>
          ))}
        </div>
      </div>

      {/* Retailers Grid */}
      <div>
        <div className="flex items-center justify-between mb-3">
          <div className="flex items-center gap-2">
            <div className="w-1 h-4 rounded-full bg-blue-500" />
            <h3 className="text-white font-semibold text-sm font-heading">
              {filteredRetailers.length} Retailers Mapped · {region}
            </h3>
          </div>
          <span className="text-white/40 text-xs">Ranked by mission fit score</span>
        </div>

        <div className="space-y-3">
          {filteredRetailers.map((retailer) => {
            const tc = tierColors[retailer.tier];
            const isExpanded = selectedRetailer?.id === retailer.id;

            return (
              <div key={retailer.id} className="rounded-2xl overflow-hidden transition-all duration-300"
                style={{
                  background: isExpanded ? "rgba(59,130,246,0.06)" : "rgba(255,255,255,0.04)",
                  border: isExpanded ? "1px solid rgba(59,130,246,0.3)" : "1px solid rgba(255,255,255,0.07)",
                }}>

                {/* Retailer Row */}
                <button
                  className="w-full flex items-center gap-4 p-4 hover:bg-white/[0.02] transition-all"
                  onClick={() => setSelectedRetailer(isExpanded ? null : retailer)}
                >
                  <div className="w-10 h-10 rounded-xl flex items-center justify-center flex-shrink-0"
                    style={{ background: "rgba(255,255,255,0.06)" }}>
                    <span className="text-white/60 text-sm font-bold">
                      {retailer.name.split(" ").map((w) => w[0]).join("").slice(0, 2)}
                    </span>
                  </div>

                  <div className="flex-1 text-left min-w-0">
                    <div className="flex items-center gap-2 flex-wrap">
                      <span className="text-white font-semibold text-sm">{retailer.name}</span>
                      <span className="px-1.5 py-0.5 rounded text-[10px] font-semibold"
                        style={{ background: tc.bg, border: `1px solid ${tc.border}`, color: tc.color }}>
                        {retailer.tier}
                      </span>
                    </div>
                    <div className="flex items-center gap-1 mt-0.5">
                      <MapPin className="w-2.5 h-2.5 text-white/30" />
                      <span className="text-white/40 text-xs">{retailer.location}</span>
                    </div>
                  </div>

                  <div className="flex items-center gap-5 flex-shrink-0 flex-wrap justify-end">
                    <div className="text-right hidden sm:block">
                      <div className="text-white/60 text-[10px] mb-0.5">Mission Fit</div>
                      <div className="flex items-center gap-1">
                        <div className="w-20 h-1.5 rounded-full overflow-hidden" style={{ background: "rgba(255,255,255,0.08)" }}>
                          <div className="h-full rounded-full" style={{ width: `${retailer.missionFit}%`, background: "#3b82f6" }} />
                        </div>
                        <span className="text-blue-400 text-xs font-bold">{retailer.missionFit}%</span>
                      </div>
                    </div>
                    <div className="text-right hidden sm:block">
                      <div className="text-white/60 text-[10px] mb-0.5">Target Customers</div>
                      <div className="text-white font-bold text-sm">{retailer.targetCustomers}</div>
                    </div>
                    <div className="text-right hidden md:block">
                      <div className="text-white/60 text-[10px] mb-0.5">Proj. Revenue</div>
                      <div className="text-green-400 font-bold text-sm">{retailer.projectedRevenue}</div>
                    </div>
                    <ChevronRight className={cn(
                      "w-4 h-4 text-white/30 transition-transform duration-200",
                      isExpanded && "rotate-90"
                    )} />
                  </div>
                </button>

                {/* Expanded Customers */}
                {isExpanded && (
                  <div className="border-t border-white/[0.06] p-4">
                    <div className="flex items-center gap-2 mb-3">
                      <Users className="w-3.5 h-3.5 text-white/40" />
                      <span className="text-white/50 text-xs font-medium uppercase tracking-wider">
                        {retailer.customers.length} Perfect-Fit Customers
                      </span>
                    </div>
                    <div className="space-y-2">
                      {retailer.customers.map((customer) => (
                        <CustomerRow
                          key={customer.id}
                          customer={customer}
                          missionColor={mission.color}
                          onClick={() => setSelectedCustomer(customer)}
                        />
                      ))}
                    </div>
                  </div>
                )}
              </div>
            );
          })}
        </div>
      </div>

      {/* Customer Profile Modal */}
      {selectedCustomer && selectedRetailer && (
        <CustomerModal
          customer={selectedCustomer}
          retailer={selectedRetailer}
          mission={mission}
          scriptGenerated={scriptGenerated}
          generatingScript={generatingScript}
          onGenerateScript={() => handleGenerateScript(selectedCustomer)}
          onClose={() => { setSelectedCustomer(null); setScriptGenerated(null); }}
        />
      )}
    </div>
  );
}

