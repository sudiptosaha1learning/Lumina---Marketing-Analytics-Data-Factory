// ─── Customer Modal ───────────────────────────────────────────────────────────

interface CustomerModalProps {
  customer: CustomerProfile;
  retailer: RetailerData;
  mission: Mission;
  scriptGenerated: string | null;
  generatingScript: boolean;
  onGenerateScript: () => void;
  onClose: () => void;
}

